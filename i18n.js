  function t(s, vars) {
    var out = s;
    if (LANG !== "en" && !(LEGAL.indexOf(s) !== -1 && !HUMAN_OK[s])) {
      if (Object.prototype.hasOwnProperty.call(ES, s)) out = ES[s];
    }
    if (vars) Object.keys(vars).forEach(function (k) { out = out.split("{" + k + "}").join(vars[k]); });
    return out;
  }
  window.t = t;

  /* Static markup: elements marked data-i18n have their own
     text nodes translated in place (icons and child elements
     are left alone); data-i18n-ph translates a placeholder. */
  function applyI18n(root) {
    if (LANG === "en") return;
    (root || document).querySelectorAll("[data-i18n]").forEach(function (el) {
      var walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT);
      var nodes = [];
      while (walker.nextNode()) nodes.push(walker.currentNode);
      nodes.forEach(function (n) {
        if (n.textContent.trim()) {
          var lead = n.textContent.match(/^\s*/)[0], tail = n.textContent.match(/\s*$/)[0];
          n.textContent = lead + t(n.textContent.trim()) + tail;
        }
      });
    });
    (root || document).querySelectorAll("[data-i18n-ph]").forEach(function (el) { el.placeholder = t(el.placeholder); });
    (root || document).querySelectorAll("[data-i18n-aria]").forEach(function (el) { var a = el.getAttribute("aria-label"); if (a) el.setAttribute("aria-label", t(a)); var ti = el.getAttribute("title"); if (ti) el.setAttribute("title", t(ti)); });
    document.documentElement.setAttribute("lang", LANG);
  }
  window.applyI18n = applyI18n;
